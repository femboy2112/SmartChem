"""V0.7-FUNNEL-01: the generative-algebra funnel (Production Chemical Algebra, Round I measurement).

The v0.6 funnel measured the IDENTITY funnel (syntax -> composition -> ambiguity -> structure). This is its
0.7 continuation, the GENERATIVE funnel, measured on a predeclared benign corpus under two algebras -- the
production DEFAULT (capped-scission only) and the forcing-vertical CANDIDATE (capped-scission + Diels-Alder):

    structure represented -> transform family enumerated -> reaction type vouched -> route reaches terminal

The point is the BEFORE/AFTER denominator delta, not any single showcase target. It is not tuned to maximise a
percentage: a control target with no retron SHOULD stall at "family enumerated", and that is the meter working.

Run:  .venv/bin/python experiments/v0_7_algebra_funnel.py
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from smartchem.diels_alder import DielsAlderProvider
from smartchem.experiment.reaction_type_oracle import recognize_reaction_type
from smartchem.experiment.routes import search_routes
from smartchem.smiles import parse_smiles
from smartchem.transform_provider import (
    DEFAULT_TRANSFORM_REGISTRY,
    CappedScissionProvider,
    TransformProviderRegistry,
)

_ARTIFACT = Path(__file__).with_name("RESULTS_v0_7_algebra_funnel.md")

CANDIDATE = TransformProviderRegistry((CappedScissionProvider(), DielsAlderProvider()))
_REGISTRIES = {"default": DEFAULT_TRANSFORM_REGISTRY, "candidate": CANDIDATE}


@dataclass(frozen=True)
class Case:
    case_id: str
    target: str
    reagents: tuple[str, ...]     # small mediators the cleavage may consume
    available: tuple[str, ...]    # precursors that terminate the backward search
    note: str


# A predeclared benign corpus: DA-retron targets, a capped-scission-routable ester (the default is NOT
# empty everywhere), and DA-inapplicable controls (a saturated ring, a hostile enone near-miss).
CORPUS: tuple[Case, ...] = (
    Case("da-cyclohexene", "C1CC=CCC1", (), ("C=CC=C", "C=C"), "canonical retro-DA"),
    Case("da-methylcyclohexene", "CC1CCC=CC1", (), (), "substituted DA retron (enumerate-level)"),
    Case("da-norbornene", "C1CC2CC1C=C2", (), (), "bicyclic DA retron (enumerate-level)"),
    Case("cap-methyl-acetate", "CC(=O)OC", ("O",), ("OC", "CC(=O)O"), "capped-scission ester cleavage"),
    Case("ctl-cyclohexane", "C1CCCCC1", (), (), "control: no retron, no reagent"),
    Case("ctl-enone-nearmiss", "O=C1CCCC=C1", (), (), "hostile near-miss: ketene retro must be demoted"),
)


def _measure(case: Case, registry) -> dict:
    target = parse_smiles(case.target)
    reagents = tuple(parse_smiles(s) for s in case.reagents)
    available = tuple(parse_smiles(s) for s in case.available)
    row = {"structure": True, "family_enumerated": False, "type_vouched": False, "terminal": False}

    ets, _ = registry.enumerate(target, reagents, budget=100_000)
    row["family_enumerated"] = len(ets) > 0

    result = search_routes(target, reagents=reagents, available=available, registry=registry, max_depth=2)
    row["terminal"] = len(result.routes) > 0
    # reaction-type vouched: some generated route step is recognised by the independent oracle.
    row["type_vouched"] = any(
        recognize_reaction_type(step) is not None for route in result.routes for step in route.steps
    )
    return row


def run_funnel():
    rows = {}
    for name, registry in _REGISTRIES.items():
        agg = {"total": len(CORPUS), "structure": 0, "family_enumerated": 0, "type_vouched": 0, "terminal": 0}
        per_case = {}
        for case in CORPUS:
            m = _measure(case, registry)
            per_case[case.case_id] = m
            for k in ("structure", "family_enumerated", "type_vouched", "terminal"):
                agg[k] += int(m[k])
        rows[name] = {"aggregate": agg, "cases": per_case}
    return rows


def render_markdown(rows) -> str:
    d, c = rows["default"]["aggregate"], rows["candidate"]["aggregate"]
    lines = [
        "# v0.7 generative-algebra funnel -- before/after (DEFAULT vs candidate = +Diels-Alder)",
        "",
        "Generated by `experiments/v0_7_algebra_funnel.py`. Corpus is predeclared and benign; the meter records",
        "truth (a control with no retron stalls at 'family enumerated' -- that is correct, not a miss).",
        "",
        "## Aggregate (n cases = " + str(d["total"]) + ")",
        "",
        "| stage | DEFAULT (capped only) | CANDIDATE (+DA) |",
        "|---|---|---|",
        f"| structure represented | {d['structure']} | {c['structure']} |",
        f"| transform family enumerated | {d['family_enumerated']} | {c['family_enumerated']} |",
        f"| reaction type vouched | {d['type_vouched']} | {c['type_vouched']} |",
        f"| route reaches terminal set | {d['terminal']} | {c['terminal']} |",
        "",
        "## Per-case (CANDIDATE registry)",
        "",
        "| case | family enum | type vouched | terminal |",
        "|---|---|---|---|",
    ]
    for cid, m in rows["candidate"]["cases"].items():
        def mk(b):
            return "Y" if b else "-"
        lines.append(f"| {cid} | {mk(m['family_enumerated'])} | {mk(m['type_vouched'])} | {mk(m['terminal'])} |")
    lines.append("")
    return "\n".join(lines) + "\n"


def main() -> int:
    rows = run_funnel()
    md = render_markdown(rows)
    _ARTIFACT.write_text(md, encoding="utf-8")
    print(md)
    print(f"[wrote {_ARTIFACT}]")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
