"""V0.7-SERVICE-FUNNEL-01: the generative funnel THROUGH THE ACTUAL SERVICE (Round II production measurement).

The Round-I `v0_7_algebra_funnel` measured the wider algebra by calling `registry.enumerate` / `search_routes`
directly.  This is its production counterpart: it drives the SAME before/after corpus through the real
`build_recompile_request -> run_compilation` compiler path under two selectable algebra PROFILES -- the production
DEFAULT (`legacy-capped-v1`) and the certified route algebra (`certified-route-v07`) -- and measures:

    structure represented -> profile resolved & use-compatible -> transform family enumerated (candidates) ->
    route reaches terminal set (exit 0) -> IR/receipt agree on the selected algebra digest

The point: the improvement is in the ACTUAL compiler request, not only an experiment harness.  The selected algebra
survives into the response's `search_receipt_digest`, which MOVES between profiles for the same target.

Run:  .venv/bin/python experiments/v0_7_service_funnel.py
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from smartchem.identity_parse import InputKind
from smartchem.service import build_recompile_request, run_compilation

_ARTIFACT = Path(__file__).with_name("RESULTS_v0_7_service_funnel.md")


@dataclass(frozen=True)
class Case:
    case_id: str
    target: str
    available: tuple[str, ...]
    note: str


# A predeclared benign corpus, each target with its precursors on hand so a TERMINAL route is reachable when the
# algebra can make it: a DA adduct (only the wider algebra terminates), a capped-scission ester (BOTH terminate --
# the default is not empty), and two DA-inapplicable controls (a saturated ring, a hostile enone near-miss).
CORPUS: tuple[Case, ...] = (
    Case("da-cyclohexene", "C1CC=CCC1", ("C=CC=C", "C=C"), "retro-DA: only the wider algebra terminates"),
    Case("cap-methyl-acetate", "CC(=O)OC", ("OC", "CC(=O)O"), "capped-scission ester: both terminate"),
    Case("ctl-cyclohexane", "C1CCCCC1", (), "control: no retron, no precursor"),
    Case("ctl-enone-nearmiss", "O=C1CCCC=C1", (), "hostile near-miss: DA must stay demoted"),
)

_PROFILES = ("legacy-capped-v1", "certified-route-v07")


def _measure(case: Case, profile: str) -> dict:
    # legacy capped needs a cutting reagent; the certified algebra runs reagentless.  We give BOTH the default water
    # pool so the ONLY difference measured is the algebra (not the reagent pool) -- capped uses water, DA ignores it.
    request = build_recompile_request(
        case.target, input_kind=InputKind.SMILES, helper_reagents=("water",),
        stock_materials=case.available, algebra_profile=profile,
    )
    resp = run_compilation(request)
    return {
        "structure": resp.exit_code != 2,                    # target resolved to a structure (not INVALID)
        "family_enumerated": len(resp.candidates) > 0,       # the algebra generated at least one candidate
        "terminal": resp.exit_code == 0,                     # a complete route to the on-hand precursors
        "receipt_digest": resp.search_receipt_digest,        # the algebra bound into the receipt
        "exit_code": resp.exit_code,
    }


def run_funnel():
    rows = {}
    for profile in _PROFILES:
        agg = {"total": len(CORPUS), "structure": 0, "family_enumerated": 0, "terminal": 0}
        per_case = {}
        for case in CORPUS:
            m = _measure(case, profile)
            per_case[case.case_id] = m
            for k in ("structure", "family_enumerated", "terminal"):
                agg[k] += int(m[k])
        rows[profile] = {"aggregate": agg, "cases": per_case}
    # the production-integration proof: for the DA target the receipt digest MOVES between profiles.
    da = "da-cyclohexene"
    rows["_receipt_binds_algebra"] = (
        rows["legacy-capped-v1"]["cases"][da]["receipt_digest"]
        != rows["certified-route-v07"]["cases"][da]["receipt_digest"]
    )
    return rows


def render_markdown(rows) -> str:
    lg, ct = rows["legacy-capped-v1"]["aggregate"], rows["certified-route-v07"]["aggregate"]
    lines = [
        "# v0.7 production-service funnel -- before/after through run_compilation (legacy vs certified-route-v07)",
        "",
        "Generated by `experiments/v0_7_service_funnel.py`. The corpus is driven through the REAL compiler request",
        "path; the selected algebra is a request field, not an experiment override.",
        "",
        f"## Aggregate (n cases = {lg['total']})",
        "",
        "| stage | legacy-capped-v1 | certified-route-v07 |",
        "|---|---|---|",
        f"| structure represented | {lg['structure']} | {ct['structure']} |",
        f"| transform family enumerated (candidates) | {lg['family_enumerated']} | {ct['family_enumerated']} |",
        f"| route reaches terminal set (exit 0) | {lg['terminal']} | {ct['terminal']} |",
        "",
        f"**Receipt binds the selected algebra** (the DA target's `search_receipt_digest` differs between profiles): "
        f"{rows['_receipt_binds_algebra']}",
        "",
        "## Per-case (certified-route-v07)",
        "",
        "| case | exit | family enum | terminal |",
        "|---|---|---|---|",
    ]
    for cid, m in rows["certified-route-v07"]["cases"].items():
        mk = lambda b: "Y" if b else "-"  # noqa: E731
        lines.append(f"| {cid} | {m['exit_code']} | {mk(m['family_enumerated'])} | {mk(m['terminal'])} |")
    lines.append("")
    return "\n".join(lines) + "\n"


def main() -> int:
    rows = run_funnel()
    md = render_markdown(rows)
    _ARTIFACT.write_text(md, encoding="utf-8")
    print(md)
    print(f"[wrote {_ARTIFACT}]")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
