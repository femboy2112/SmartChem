"""V0.9-SOURCE-MAP-01 (Round V, F73): the committed source map of every curated material interval.

*Listen:* an interval nobody can trace is a vibe with a decimal point. Round V (D7/D8) bound every production
``MaterialComponent`` interval to a digestible :class:`~smartchem.data.derived_evidence.IntervalEvidence` record
(closed kernel, typed inputs, source locators) or relabelled it ASSUMED/UNKNOWN; this harness makes that claim
CHECKABLE instead of scratch-only. For every curated bottle in :mod:`smartchem.data.material_library` it emits one row
per component: the interval, its basis, the evidence kind, the kernel, and every typed input with its unit, kind and
source locator -- and it fails loudly if any component carries no record at all.

Run:  .venv/bin/python experiments/v0_9_material_source_map.py > docs/research/V0_9_RC_ROUND_V_MATERIAL_SOURCE_MAP.md
"""
from __future__ import annotations

import inspect
import sys

from smartchem.data import material_library as ml
from smartchem.experiment.stock import StockMaterial


def curated_bottles() -> "list[StockMaterial]":
    """Every public zero-argument material-library builder that returns ONE StockMaterial (the curated bottles)."""
    out: "list[StockMaterial]" = []
    for name in ml.__all__:
        fn = getattr(ml, name)
        if not callable(fn):
            continue
        params = inspect.signature(fn).parameters.values()
        if any(p.default is inspect.Parameter.empty for p in params):
            continue
        obj = fn()
        if type(obj) is StockMaterial:
            out.append(obj)
    return out


def rows() -> "list[dict]":
    table = []
    for bottle in curated_bottles():
        for comp in bottle.components:
            ev = comp.evidence
            table.append({
                "bottle": bottle.material_id,
                "component": comp.identity_key,
                "role": comp.role,
                "interval": (comp.min_fraction, comp.max_fraction),
                "basis": comp.basis.value,
                "kind": ev.kind.value if ev is not None else "NONE",
                "kernel": ev.kernel.value if ev is not None else "-",
                "locators": tuple(ev.source_locators) if ev is not None else (),
                "inputs": tuple(
                    f"{i.name}={i.value} {i.unit.value} [{i.kind.value}]"
                    + (f" @ {i.source_locator}" if i.source_locator else "")
                    + (f" (T={i.temperature_k} K)" if i.temperature_k else "")
                    for i in ev.inputs) if ev is not None else (),
                "domain": ev.domain_of_validity if ev is not None else "",
            })
    return table


def main() -> int:
    table = rows()
    missing = [r for r in table if r["kind"] == "NONE"]
    print("# Round V — curated material source map (F73)\n")
    print("Generated by `experiments/v0_9_material_source_map.py` from `smartchem/data/material_library.py`. Every")
    print("component interval of every curated bench bottle, with the IntervalEvidence record that justifies it. ASSUMED")
    print("and UNKNOWN records are listed as such — they certify nothing (D6/F71); they are here so nobody mistakes them")
    print("for sourced facts. The library is an EXAMPLE declared world authored by the repository (D24.10).\n")
    print(f"Components: {len(table)}; with a record: {len(table) - len(missing)}; without: {len(missing)}.\n")
    print("| bottle | component | role | interval | basis | evidence | kernel | source locators | typed inputs |")
    print("|---|---|---|---|---|---|---|---|---|")
    for r in table:
        lo, hi = r["interval"]
        print(f"| `{r['bottle']}` | `{r['component'][:28]}` | {r['role']} | [{lo:g}, {hi:g}] | {r['basis']} | "
              f"{r['kind']} | `{r['kernel']}` | {'<br>'.join(r['locators']) or '—'} | "
              f"{'<br>'.join(r['inputs']) or '—'} |")
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
