"""
Vendored correlation-consistent basis sets with tight d functions, for Al-Ar.

Why this file exists
--------------------
The standard cc-pVXZ sets under-describe second-row elements: their 3d orbitals sit low
enough that d-correlation is not saturated, and the deficiency does not vanish under
basis-set extrapolation because it is a defect present at every cardinal. Dunning,
Peterson and Wilson (J. Chem. Phys. 114, 9244 (2001)) added tight d functions to fix it.

PySCF 2.14 ships only the double-zeta member of that family (cc-pV(D+d)Z), which is no use
for a TZ/QZ extrapolation. The four sets needed for the aug-cbs(TZ,QZ) tier are vendored
here so the benchmark reproduces from this repository alone -- no network fetch, no extra
runtime dependency. Text is verbatim NWChem output from the Basis Set Exchange, including
its provenance header; the "#BASIS SET:" comment lines are load-bearing delimiters for
``pyscf.gto.basis.parse``, so do not strip comments from these blocks.

MEASURED contribution, not assumed
----------------------------------
Tight d is worth including, but it is NOT the dominant correction -- which is what an
earlier version of these docs claimed on the strength of the literature pattern rather
than a measurement. Discriminating probe at fixed cardinal (CCSD(T)/TZ), signed error vs
experiment in kcal/mol:

    species   plain    +diffuse   +tight d   +both
    CS        -6.56      -3.80      -5.17     -2.44
    NaCl      -4.10      -1.11      -4.07     -1.11

For CS, diffuse functions are worth +2.76 and tight d only +1.39; the two are very nearly
additive (4.15 predicted vs 4.12 observed). For ionic NaCl, tight d on chlorine is worth
+0.03 -- nothing at all. The claim "CS misses because sulfur wants tight d" was testimony
borrowed from the literature, and the probe built to test it found diffuse functions to be
the larger term.

Source
------
Basis Set Exchange (basissetexchange.org), MolSSI, retrieved via the ``basis_set_exchange``
Python package v0.12 on 2026-07-20. Underlying data: ccRepo / Grant Hill.

Regenerate with (``pip install basis_set_exchange``; it is NOT a runtime dependency)::

    import basis_set_exchange as bse
    ELS = ['Al', 'Si', 'P', 'S', 'Cl', 'Ar']
    for name in ['cc-pV(T+d)Z', 'cc-pV(Q+d)Z',
                 'aug-cc-pV(T+d)Z', 'aug-cc-pV(Q+d)Z']:
        block = bse.get_basis(name, elements=ELS, fmt='nwchem')   # keep comments!

Only T+d and Q+d are vendored, because only those two feed the aug-cbs(TZ,QZ) tier.
``resolve_basis`` falls back to the standard set at any other cardinal rather than
substituting a different one.
"""
